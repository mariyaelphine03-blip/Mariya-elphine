export function generateSyntheticCampaigns(count = 50): Campaign[] {
  const channels: Array<Campaign['channel']> = ["Google Ads", "Meta Ads", "LinkedIn", "TikTok", "YouTube", "Email"];
  const objectives: Array<Campaign['target_objective']> = ["Sales", "Lead Gen", "Traffic", "Awareness"];

  const results: Campaign[] = [];

  for (let i = 1; i <= count; i++) {
    const channel = channels[Math.floor(Math.random() * channels.length)];
    const audience_type: Campaign['audience_type'] = channel === "LinkedIn" ? "B2B" : (Math.random() > 0.3 ? "B2C" : "B2B");
    const target_objective = objectives[Math.floor(Math.random() * objectives.length)];

    let spend = Math.round(500 + Math.random() * 9500);
    let cpc = 1.0;
    let ctr = 2.5;

    if (channel === "LinkedIn") {
      cpc = Number((4.5 + Math.random() * 5.0).toFixed(2));
      ctr = Number((1.2 + Math.random() * 0.8).toFixed(2));
    } else if (channel === "TikTok") {
      cpc = Number((0.4 + Math.random() * 0.5).toFixed(2));
      ctr = Number((1.8 + Math.random() * 1.5).toFixed(2));
    } else if (channel === "Email") {
      cpc = Number((0.18 + Math.random() * 0.15).toFixed(2));
      ctr = Number((5.5 + Math.random() * 3.5).toFixed(2));
      spend = Math.round(300 + Math.random() * 700);
    } else if (channel === "Google Ads") {
      cpc = Number((0.9 + Math.random() * 2.2).toFixed(2));
      ctr = Number((2.8 + Math.random() * 2.0).toFixed(2));
    } else if (channel === "YouTube") {
      cpc = Number((1.3 + Math.random() * 1.6).toFixed(2));
      ctr = Number((1.7 + Math.random() * 1.2).toFixed(2));
    } else {
      // Meta
      cpc = Number((0.9 + Math.random() * 1.1).toFixed(2));
      ctr = Number((2.4 + Math.random() * 1.4).toFixed(2));
    }

    const clicks = Math.max(10, Math.round(spend / cpc));
    const impressions = Math.round((clicks / (ctr / 100)));
    const cvr = Number((audience_type === "B2C" ? (4.0 + Math.random() * 6.5) : (5.0 + Math.random() * 4.5)).toFixed(2));
    const conversions = Math.max(1, Math.round(clicks * (cvr / 100)));
    const aov = audience_type === "B2C" ? (55 + Math.random() * 35) : (220 + Math.random() * 180);
    const revenue = Math.round(conversions * aov);
    const roas = Number((revenue / spend).toFixed(2));
    const creative_quality_score = Number((5.0 + Math.random() * 4.8).toFixed(1));

    let performance_tier: PerformanceTier = 'Medium';
    if (roas >= 3.5) performance_tier = 'High';
    else if (roas < 2.0) performance_tier = 'Low';

    results.push({
      campaign_id: `CMP-${2000 + i}`,
      campaign_name: `${channel} Auto Run ${i}`,
      channel,
      audience_type,
      ad_spend: spend,
      impressions,
      clicks,
      ctr,
      cpc,
      conversions,
      conversion_rate: cvr,
      revenue,
      roas,
      creative_quality_score,
      target_objective,
      performance_tier
    });
  }

  return results;
}
